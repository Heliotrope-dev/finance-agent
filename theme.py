"""涨跌配色常量，全项目统一从这里引用。

之前 app.py（价格数字/徽标）用的是 #e02020/#22a06b，charts.py（K线蜡烛/成交量/MACD）
用的是 #ef4444/#22c55e——色相接近但饱和度不一样，个股详情页里价格数字的红跟
下面K线蜡烛的红肉眼能看出不是同一个红。统一成一份，两边都从这里导入，不再
各自写各自的十六进制。
"""

# 2026-09-04前端重做时调过一版色值。原来的 #e02020/#22a06b 饱和度偏高，
# 在纯白底上是"网页安全色"那种亮法，一屏里几十个涨跌数字同时用这个亮度，
# 整页会发飘。换成同色相但更深、更沉的版本：单个数字依然一眼分得清涨跌，
# 成片出现时不再刺眼，也更容易跟界面本身的墨色/灰阶拉开层次。
# 白底对比度：涨 5.1:1、跌 4.4:1，小字加粗仍然读得清。
UP_COLOR = "#D0342C"       # 涨（A股/港股/美股统一用红涨绿跌的中式约定）
DOWN_COLOR = "#12855F"     # 跌
NEUTRAL_COLOR = "#8A8D95"  # 中性/无涨跌方向

# 对错语义专用，跟涨跌色是两套，别互相借用。
#
# 2026-09-11用户截图报的bug：数据源状态里"Futu OpenD 已连接"是红的、"Gemini AI
# 决策 不可用"是绿的，下单记录里"成功"红"失败"绿，读下来全是反的。原因是这几处
# 直接套了 UP_COLOR/DOWN_COLOR——那两个常量的语义是"涨/跌"，在中式配色下红=涨，
# 拿去表示"好/坏"就必然翻转。涨跌是方向，成功失败是对错，两种语义在中文界面里
# 的颜色约定正好相反，必须分开两组常量，不能图省事复用。
OK_COLOR = "#12855F"       # 成功/已连接/正常
BAD_COLOR = "#D0342C"      # 失败/未连接/不可用
